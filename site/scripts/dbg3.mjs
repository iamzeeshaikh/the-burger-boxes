import { chromium } from 'playwright';
const base='https://site-dun-ten-91.vercel.app';
const b=await chromium.launch();
const p=await (await b.newContext({viewport:{width:1440,height:900}})).newPage();
p.on('pageerror',e=>console.log('ERR',e.message));
await p.goto(base+'/product/black-burger-boxes/',{waitUntil:'load'});
await p.waitForTimeout(2500);
await p.locator('a.elementor-button[href*="add-to-cart="]').first().scrollIntoViewIfNeeded();
await p.locator('a.elementor-button[href*="add-to-cart="]').first().click();
await p.waitForTimeout(3000);
console.log('url', p.url());
await p.waitForSelector('a.remove[data-remove]',{timeout:15000});
console.log('rows before', await p.locator('.woocommerce-cart-form__cart-item').count());
await p.locator('a.remove[data-remove]').first().click();
await p.waitForTimeout(1500);
console.log('rows after', await p.locator('.woocommerce-cart-form__cart-item').count());
console.log('filled div exists', await p.locator('#tbb-cart-filled').count());
console.log('empty block count', await p.locator('.wp-block-woocommerce-empty-cart-block').count());
console.log('empty visible', await p.locator('.wp-block-woocommerce-empty-cart-block').first().isVisible().catch(e=>'ERR '+e.message));
console.log('empty style', await p.locator('.wp-block-woocommerce-empty-cart-block').first().evaluate(el=>el.getAttribute('style')+' | display='+getComputedStyle(el).display).catch(e=>'ERR'));
console.log('localStorage', await p.evaluate(()=>localStorage.getItem('tbb_cart')));
await b.close();
